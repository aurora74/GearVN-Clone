function toBinaryQrels(
  benchmarkCase: BenchmarkCase,
  productIds: string[],
): BenchmarkBinaryQrel[] {
  return productIds.map((productId) => ({
    productId,
    relevant: true,
    rationale: `Binary relevant product label for ${benchmarkCase.id} (${benchmarkCase.group}) based on the Chapter 4 benchmark artifact review.`,
  }));
}

export const productRetrievalBenchmarkCases: BenchmarkCase[] =
  chapter4BaseProductRetrievalBenchmarkCases.map((benchmarkCase) => {
    if (benchmarkCase.expectedClarification === true) return benchmarkCase;

    const productIds = chapter4BinaryProductIdsByCaseId[benchmarkCase.id] ?? [];
    if (productIds.length === 0) return benchmarkCase;

    if (manualBinaryQrelGroups.has(benchmarkCase.group)) {
      return {
        ...benchmarkCase,
        expectedQrels: toBinaryQrels(benchmarkCase, productIds),
      };
    }

    return {
      ...benchmarkCase,
      expectedProductIds: productIds,
    };
  });
